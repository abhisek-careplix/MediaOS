// Pre-production: a brief and product references → three creative concepts → a cast, locations and a shot list →
// a storyboard frame per shot (drawn by Claude as a pencil-and-marker sketch, the real product photo placed into it)
// → an animatic (a quick film made from the boards with a temp voice and music; see templates/animatic).
// A production lives in a film folder (FILMS/p-…) as production.json, boards/ (one frame per shot), cast/ (character
// reference portraits) and media/ (the product photos).
// Frames come in three styles: a sketch Claude draws as SVG (free, no other service), or an illustrated storyboard or a
// cinematic still generated by Vertex AI from each character's reference portrait and the real product photo.
// Then the shoot: each frame becomes video (lib/video.mjs). Every spoken line is recorded once in its speaker's studio
// voice (lib/voice.mjs); a presenter shot is performed from its frame and that very recording, lips in time; each take
// is checked against the cast's portraits and the product photo, and gets its own bed of room tone (lib/sound.mjs).
// The cut adds a composed score the length of the film.
