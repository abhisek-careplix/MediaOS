// Pre-production: a brief and product references → three creative concepts → a cast, locations and a shot list →
// a storyboard frame per shot (drawn by Claude as a pencil-and-marker sketch, the real product photo placed into it)
// → an animatic (a quick film made from the boards with a temp voice and music; see templates/animatic).
// A production lives in a film folder (FILMS/p-…) as production.json, boards/ (one frame per shot), cast/ (character
// reference portraits) and media/ (the product photos).
// Frames come in three styles: a sketch Claude draws as SVG (free, no other service), or an illustrated storyboard or a
// cinematic still generated by Vertex AI from each character's reference portrait and the real product photo.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { askJSON, KIND } from './claude.mjs';
import { generateImage } from './vertex.mjs';
import { readBrand } from './brands.mjs';
import { proofForPrompt, unsupportedNumbers, listProof } from './proof.mjs';

// what each format asks of the writing and the boards
export const FORMATS = {
  influencer: { name: 'Influencer reel', what: 'creator-style (UGC) reel', brief: `A creator talks to camera in selfie framing (handheld, natural light, jump cuts), demonstrates the product, and cuts away to close-ups of it and of the app. Hook in the first two seconds, captions throughout. The creator is an actor or brand ambassador: never present them as a real customer reporting their own results, and never as a doctor.` },
  brand: { name: 'Brand film', what: 'cinematic brand ad film', brief: `A short cinematic story with characters: a situation the audience recognises, a turn, and a resolution in which the product plays its part, ending on the brand. Real film language: shot sizes, camera moves, light. Emotion over features.` },
  mascot: { name: 'Mascot story', what: 'animated mascot story', brief: `A short animated story starring a brand mascot creature (design one if the brief has none: a simple, ownable silhouette, two or three colours, a clear personality). Playful, warm, readable at a glance; the mascot shows the benefit rather than talking about it.` },
  product: { name: 'Product hero', what: 'product hero film', brief: `The product is the star: hero shots, close details, the app in use, one benefit per shot with a short on-screen line, ending on the brand. Clean, premium, rhythmic.` },
};
export const STYLES = {
  sketch: { name: 'Sketch' },
  illustrated: { name: 'Illustrated', vertex: true, look: 'A professional feature-film storyboard frame: confident ink linework with soft, muted colour washes, by a top storyboard artist. Clear staging, readable silhouettes, believable light and depth.' },
  cinematic: { name: 'Cinematic', vertex: true, look: 'A photorealistic film still from a premium TV commercial: cinema camera, natural motivated light, shallow depth of field, a subtle colour grade.' },
};
const FRAME = /^(boards|cast)\/[\w-]+\.(svg|png)$/;
const mimeOf = f => ({ '.png': 'image/png', '.webp': 'image/webp' })[path.extname(f).toLowerCase()] || 'image/jpeg';
const drop = (dir, f) => { if (f && FRAME.test(f)) fs.rmSync(path.join(dir, f), { force: true }); };
const SIZES = ['Extreme wide', 'Wide', 'Medium', 'Medium close-up', 'Close-up', 'Extreme close-up', 'Insert', 'Over the shoulder', 'POV', 'Two shot'];
const MOVES = ['Static', 'Push in', 'Pull out', 'Pan left', 'Pan right', 'Tilt up', 'Tilt down', 'Tracking', 'Handheld', 'Orbit', 'Crane up'];
const ENGINES = ['video', 'presenter', 'code', 'product'];
// rough generation cost per second of finished shot, three takes each (third-party rates; refined once providers are connected)
const RATE = { video: 0.25 * 3, presenter: 0.07 * 2, code: 0, product: 0.25 * 2 };

const str = { type: 'string' };
const read = dir => JSON.parse(fs.readFileSync(path.join(dir, 'production.json'), 'utf8'));
export const readProduction = dir => { try { return read(dir); } catch { return null; } };
export function saveProduction(dir, p) {
  fs.writeFileSync(path.join(dir, 'production.json'), JSON.stringify(p, null, 1));
  return p;
}
// the photos Claude may look at: product photos in media/, references in refs/
const filesOf = (dir, p) => [
  ...(p.media || []).map((m, i) => ({ src: path.join(dir, m.src), name: `product-${i + 1}${path.extname(m.src)}` })),
  ...(p.refs || []).map((r, i) => ({ src: path.join(dir, r), name: `reference-${i + 1}${path.extname(r)}` })),
];
function context(p, dir) {
  const files = filesOf(dir, p), photos = files.filter(f => f.name.startsWith('product')), refs = files.filter(f => f.name.startsWith('reference'));
  return `${p.brand ? `The brand: "${p.brand.name}"${p.brand.tone ? `, voice: ${p.brand.tone}` : ''}.` : ''}
The brief:
"""
${p.brief}
"""
${photos.length ? `Product photos (open each with the Read tool and look at it): ${photos.map((f, i) => `./${f.name} (photo ${i})`).join(', ')}. Describe only what is visible or stated; never invent features, specifications or results.\n` : ''}${refs.length ? `Reference images (look at them; they guide tone and approach but are not shown, and another brand's wording or claims are never copied): ${refs.map(f => './' + f.name).join(', ')}.\n` : ''}${p.notes ? `Notes from the team:\n"""\n${p.notes}\n"""\n` : ''}
Approved facts (the Proof Library). Any figure or health claim must come from here or from the brief itself; otherwise say it without numbers:
${JSON.stringify(proofForPrompt())}

Rules for all advertising: never present an actor, presenter or AI character as a real customer or patient reporting their own results; no doctors or clinicians giving advice unless the brief says a real, consenting clinician is involved; never use or imitate a real or famous person's likeness or voice; never assert or imply the viewer's own health conditions or personal traits; no guaranteed or exaggerated outcomes.${KIND[p.kind]?.rules ? '\n' + KIND[p.kind].rules.trim() : ''}`;
}
const head = p => `You are the creative director of a production studio. The piece: a ${p.seconds}-second ${p.aspect === '9:16' ? 'vertical (9:16)' : 'widescreen (16:9)'} ${FORMATS[p.format].what}${p.kind === 'ad' ? ', running as a paid social ad' : p.kind === 'reel' ? ', posted as a short-form reel' : ''}.
Format: ${FORMATS[p.format].brief}`;

// —— 1. concepts ——
export async function writeConcepts(dir, p, { model = 'sonnet' } = {}) {
  const schema = { type: 'object', additionalProperties: false, required: ['concepts'], properties: { concepts: { type: 'array', minItems: 3, maxItems: 3, items: {
    type: 'object', additionalProperties: false, required: ['name', 'logline', 'hook', 'story', 'tone', 'why', 'keyframes', 'watchouts'],
    properties: { name: str, logline: str, hook: str, story: str, tone: { type: 'array', items: str, minItems: 2, maxItems: 4 }, why: str, keyframes: { type: 'array', items: str, minItems: 3, maxItems: 3 }, watchouts: str },
  } } } };
  const prompt = `${head(p)}

${context(p, dir)}

Pitch exactly three creative concepts that take genuinely different routes (for example an emotional story, a demonstration, and a surprise or humour angle), each one producible in ${p.seconds} seconds.
For each: name (2-4 words), logline (one sentence), hook (what we see and hear in the first two seconds), story (3-5 sentences: the opening, the turn, the resolution, and where the product appears), tone (2-4 single words), why (why it will work for this audience on this platform, one or two sentences), keyframes (three short visual descriptions of key moments), watchouts (claims, ad-policy, likeness or production risks to check before shooting, or "None").
Plain text only: no markdown, no emoji.`;
  const r = await askJSON(prompt, schema, { model, timeout: 300000, files: filesOf(dir, p) });
  p.concepts = [...(p.concepts || []), ...r.data.concepts];
  p.cost = (p.cost || 0) + (r.cost || 0);
  return { p, cost: r.cost };
}

// —— 2. cast, locations and shots for the chosen concept ——
export async function writeShots(dir, p, { model = 'sonnet' } = {}) {
  const c = p.concepts[p.concept];
  const live = listProof().filter(e => e.state === 'approved').map(e => e.id), photos = (p.media || []).length;
  const n = Math.max(4, Math.min(16, Math.round(p.seconds / 2.6)));
  const schema = { type: 'object', additionalProperties: false, required: ['title', 'music', 'cast', 'locations', 'shots'], properties: {
    title: str,
    music: { type: 'object', additionalProperties: false, required: ['mood', 'bpm'], properties: { mood: str, bpm: { type: 'integer', minimum: 70, maximum: 132 } } },
    cast: { type: 'array', maxItems: 4, items: { type: 'object', additionalProperties: false, required: ['id', 'name', 'look', 'wardrobe', 'voice'], properties: { id: str, name: str, look: str, wardrobe: str, voice: str } } },
    locations: { type: 'array', maxItems: 4, items: { type: 'object', additionalProperties: false, required: ['id', 'name', 'look'], properties: { id: str, name: str, look: str } } },
    shots: { type: 'array', minItems: Math.max(3, n - 3), maxItems: n + 3, items: {
      type: 'object', additionalProperties: false, required: ['size', 'angle', 'move', 'dur', 'engine', 'action', 'vo', 'super', 'cast', 'location', 'product', 'proof'],
      properties: {
        size: { type: 'string', enum: SIZES }, angle: str, move: { type: 'string', enum: MOVES }, dur: { type: 'number', minimum: 1, maximum: 8 },
        engine: { type: 'string', enum: ENGINES }, action: str, vo: str, super: str,
        cast: { type: 'array', items: str }, location: str,
        product: { type: 'integer', minimum: -1, maximum: photos - 1 },
        proof: { type: 'array', items: live.length ? { type: 'string', enum: live } : str, maxItems: live.length ? 4 : 0 },
      },
    } },
  } };
  const prompt = `${head(p)}

${context(p, dir)}

The chosen concept:
${JSON.stringify(c)}

Now plan the production as its director.
- title: the piece's working title.
- music: the score's mood in a few words, and its tempo.
- cast: every recurring character once, invented people (or creatures) only: id (c1, c2…), name, look (age range, build, skin tone, hair, face, distinctive features — specific enough to draw the same person in every frame), wardrobe, voice. A mascot gets an exact design: silhouette, colours, features.
- locations: id (l1, l2…), name, look (time of day, light, palette, key set pieces).
- shots: about ${n} shots whose durations add up to about ${p.seconds} seconds. For each: size, angle (a few words), move, dur (seconds), engine, action (what we see, one or two concrete sentences a storyboard artist can draw), vo (the spoken line during this shot, or "" — narration or the presenter's words), super (short on-screen text, or ""), cast (ids in frame), location (id, or ""), product (${photos ? `which product photo is visible, 0-${photos - 1}, or -1` : '-1: there are no product photos'}), proof (ids of the Proof Library entries any claim in vo or super relies on).
- engine: "video" for a filmed or animated scene (generated later), "presenter" for someone speaking to camera, "code" for motion graphics (text, data, UI, logo, end card), "product" for a real product photo or app screen as the hero.
- Open on the concept's hook. End on a "code" end card with the brand and the call to action.
- Spoken lines: about 2.4 words per second of their shot at most; natural spoken English.
Plain text only: no markdown, no emoji.`;
  const r = await askJSON(prompt, schema, { model, timeout: 400000, files: filesOf(dir, p) });
  const d = r.data;
  Object.assign(p, { title: d.title, music: d.music, cast: d.cast, locations: d.locations });
  p.shots = d.shots.map((s, i) => ({ id: 's' + (i + 1) + '-' + Math.random().toString(36).slice(2, 5), ...s, product: s.product >= 0 && s.product < photos ? s.product : -1, board: null, box: null }));
  p.cost = (p.cost || 0) + (r.cost || 0);
  return { p, cost: r.cost };
}

// —— 3. a storyboard frame ——
// SVG from the model is cleaned before it is stored: only drawing elements and presentation attributes survive
const TAGS = new Set(['svg', 'g', 'path', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon', 'defs', 'lineargradient', 'radialgradient', 'stop', 'clippath', 'mask', 'use', 'pattern',
  'filter', 'fegaussianblur', 'feoffset', 'feblend', 'fecolormatrix', 'fecomposite', 'femerge', 'femergenode', 'feflood', 'feturbulence', 'fedisplacementmap', 'title', 'desc']);
export function cleanSVG(svg, w, h) {
  let s = String(svg || '');
  s = s.replace(/<(script|style|foreignObject|iframe|image|a)\b[\s\S]*?<\/\1\s*>/gi, '').replace(/<(script|style|foreignObject|iframe|image|a)\b[^>]*\/?>/gi, '');
  s = s.replace(/<!--[\s\S]*?-->|<!\[CDATA\[[\s\S]*?\]\]>|<\?[\s\S]*?\?>|<!DOCTYPE[^>]*>/gi, '');
  s = s.replace(/<\/?([a-zA-Z][\w:-]*)\b[^>]*>/g, (tag, name) => TAGS.has(name.toLowerCase()) ? tag : '');
  s = s.replace(/\s(on\w+|style)\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, '');
  // references stay inside the drawing
  s = s.replace(/\s((?:xlink:)?href)\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, (m, k, v) => /^["']?#/.test(v) ? m : '');
  s = s.replace(/url\(\s*(?!['"]?#)[^)]*\)/gi, 'none').replace(/javascript:/gi, '');
  const body = s.replace(/^[\s\S]*?<svg\b[^>]*>/i, '').replace(/<\/svg>\s*$/i, '');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><rect width="${w}" height="${h}" fill="#fbfaf7"/>${body}</svg>`;
}

export async function drawBoard(dir, p, shot, opts = {}) {
  if (!STYLES[p.style]?.vertex) return { ...(await drawSketch(dir, p, shot, opts)), fallback: null };
  // graphics (end cards, supers) are never generated: a model invents logos and lettering; the real logo goes on in the animatic
  if (shot.engine === 'code') return { ...brandCard(dir, p, shot), fallback: null };
  // a refused frame (a safety block, say) becomes a sketch; a busy service is reported, and the shot keeps its frame
  try { return { ...(await drawFrame(dir, p, shot, opts)), fallback: null }; }
  catch (e) {
    if (e.code === 429 || e.code >= 500) throw e;
    return { ...(await drawSketch(dir, p, shot, opts)), fallback: String(e.message || e).slice(0, 200) };
  }
}

async function drawSketch(dir, p, shot, { note = '', model = 'sonnet' } = {}) {
  const [w, h] = p.aspect === '9:16' ? [900, 1600] : [1600, 900];
  const cast = (p.cast || []).filter(c => shot.cast?.includes(c.id)), loc = (p.locations || []).find(l => l.id === shot.location);
  const schema = { type: 'object', additionalProperties: false, required: ['svg', 'product'], properties: {
    svg: str,
    product: { anyOf: [{ type: 'null' }, { type: 'object', additionalProperties: false, required: ['x', 'y', 'w', 'h'], properties: { x: { type: 'number' }, y: { type: 'number' }, w: { type: 'number' }, h: { type: 'number' } } }] },
  } };
  const kind = { video: 'a live-action (or animated) scene', presenter: 'a person speaking straight to camera', code: 'a motion-graphics frame: lay out the text blocks as lines and bars, UI panels and the logo position as simple boxes', product: 'a product hero shot' }[shot.engine];
  const prompt = `You are a storyboard artist. Draw one storyboard frame as SVG: viewBox 0 0 ${w} ${h} (${p.aspect === '9:16' ? 'vertical 9:16' : '16:9'}).
Style: a professional pencil-and-marker storyboard sketch. Greyscale only: strokes #222 to #555, fills from #f4f4f4 (light) to #9a9a9a (shadow); paper background #fbfaf7. Confident simplified shapes, clear silhouettes, depth and light; people with believable proportions (never stick figures); creatures with a clear, appealing design. No text or lettering, no captions, no frame border: those are added later.
Compose exactly for the shot size, angle and camera move, as a cinematographer would${p.aspect === '9:16' ? ' for a phone screen' : ''}.
This is ${kind}.
${shot.product >= 0 ? 'The real product photo will be placed over a rectangle you choose: return its box in product {x, y, w, h} (viewBox units) where the product (or the phone screen showing it) appears, and keep that area a plain light rectangle.' : 'No product photo in this shot: product is null.'}
${cast.length ? `Characters (draw them exactly so, the same in every frame): ${cast.map(c => `${c.name}: ${c.look}; wears ${c.wardrobe}`).join(' | ')}` : 'No characters.'}
${loc ? `Location: ${loc.name}: ${loc.look}` : ''}
Shot: ${shot.size}, ${shot.angle}, camera ${shot.move}, ${shot.dur} s.
Action: ${shot.action}
${note ? `Director's note for this redraw: ${note}` : ''}
Return one <svg> element (no scripts, no images, no text) and the product box.`;
  const r = await askJSON(prompt, schema, { model, timeout: 240000 });
  const name = `boards/${shot.id}-${Date.now().toString(36)}.svg`;
  fs.mkdirSync(path.join(dir, 'boards'), { recursive: true });
  fs.writeFileSync(path.join(dir, name), cleanSVG(r.data.svg, w, h));
  drop(dir, shot.board);
  const b = r.data.product, clampBox = b && shot.product >= 0 ? { x: Math.max(0, Math.min(w, b.x)), y: Math.max(0, Math.min(h, b.y)), w: Math.max(20, Math.min(w, b.w)), h: Math.max(20, Math.min(h, b.h)) } : null;
  return { board: name, box: clampBox, cost: r.cost };
}

// a clean card in the brand's colours for a graphics shot: its background, two soft accent shapes, room for the logo
function brandCard(dir, p, shot) {
  const [w, h] = p.aspect === '9:16' ? [900, 1600] : [1600, 900];
  const c = (p.brandId && readBrand(p.brandId)?.colors) || { bg: '#f4f5f7', surface: '#e9ebef', accent: '#0a84ff' };
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><rect width="${w}" height="${h}" fill="${c.bg}"/>`
    + `<circle cx="${w * 0.86}" cy="${h * 0.12}" r="${Math.min(w, h) * 0.42}" fill="${c.surface}"/><circle cx="${w * 0.08}" cy="${h * 0.95}" r="${Math.min(w, h) * 0.3}" fill="${c.accent}" opacity="0.12"/></svg>`;
  const name = `boards/${shot.id}-${Date.now().toString(36)}.svg`;
  fs.mkdirSync(path.join(dir, 'boards'), { recursive: true });
  fs.writeFileSync(path.join(dir, name), cleanSVG(svg, w, h));
  drop(dir, shot.board);
  return { board: name, box: null, cost: 0 };
}

// —— generated frames (Vertex AI) ——
// each character once, as a reference portrait in the production's style; redone when their look or the style changes
export async function ensureCast(dir) {
  const p = read(dir), st = STYLES[p.style];
  if (!st?.vertex) return 0;
  const todo = (p.cast || []).filter(c => c.refKey !== key(p, c));
  let cost = 0;
  await Promise.all(todo.map(async c => {
    const r = await generateImage({ aspect: '1:1', prompt: `${st.look}
A character reference portrait for this production, one character only: ${c.name}: ${c.look}. Wearing ${c.wardrobe}.
Waist-up, three-quarter view, a natural expression, a plain light-grey backdrop, soft even light. No text, no other people or creatures.` });
    const name = `cast/${c.id.replace(/\W/g, '')}-${Date.now().toString(36)}.png`;
    fs.mkdirSync(path.join(dir, 'cast'), { recursive: true });
    fs.writeFileSync(path.join(dir, name), r.png);
    cost += r.cost;
    const fresh = read(dir), x = fresh.cast.find(y => y.id === c.id);
    if (x) { drop(dir, x.ref); Object.assign(x, { ref: name, refKey: key(fresh, x) }); fresh.cost = (fresh.cost || 0) + r.cost; saveProduction(dir, fresh); }
  }));
  return cost;
}
const key = (p, c) => crypto.createHash('sha1').update([p.style, c.look, c.wardrobe].join('|')).digest('hex').slice(0, 12);

async function drawFrame(dir, p, shot, { note = '' } = {}) {
  const st = STYLES[p.style], loc = (p.locations || []).find(l => l.id === shot.location);
  const cast = (p.cast || []).filter(c => shot.cast?.includes(c.id));
  const photo = shot.product >= 0 ? p.media?.[shot.product] : null;
  // up to three references: the product first, then the characters in frame
  const refs = [];
  if (photo) refs.push({ mime: mimeOf(photo.src), data: fs.readFileSync(path.join(dir, photo.src)), what: 'the product: show it exactly as in this photo (shape, colours, the screen)' });
  for (const c of cast) if (c.ref && refs.length < 3) refs.push({ mime: 'image/png', data: fs.readFileSync(path.join(dir, c.ref)), what: `${c.name}: the same face, hair, build and clothes` });
  const prompt = `${st.look}
One ${p.aspect === '9:16' ? 'vertical 9:16' : '16:9'} frame. No text, captions, subtitles, logos, watermarks or panel borders${photo ? ', apart from what is on the product itself' : ''}.
${refs.length ? `Reference images, in order: ${refs.map((r, i) => `image ${i + 1} is ${r.what}`).join('; ')}.` : ''}
Shot: ${shot.size}, ${shot.angle}, camera ${shot.move}.${shot.engine === 'presenter' ? ' The person speaks straight to camera, phone-camera framing.' : ''}
${loc ? `Location: ${loc.name}: ${loc.look}.` : ''}
${cast.length ? `In frame: ${cast.map(c => `${c.name} (${c.look}; wearing ${c.wardrobe})`).join('; ')}.` : 'No people in frame unless the action needs them.'}
Action: ${shot.action}
${shot.engine === 'code' ? 'This is a motion-graphics card: a clean, minimal branded layout with abstract shapes and empty space where text will go; no lettering.' : ''}
${note ? `Director's note: ${note}` : ''}`;
  const r = await generateImage({ prompt, refs, aspect: p.aspect });
  const name = `boards/${shot.id}-${Date.now().toString(36)}.png`;
  fs.mkdirSync(path.join(dir, 'boards'), { recursive: true });
  fs.writeFileSync(path.join(dir, name), r.png);
  drop(dir, shot.board);
  return { board: name, box: null, cost: r.cost };
}

// a few at a time, each frame saved and reported as it lands
export async function drawBoards(dir, ids, { onShot, onStep, model } = {}) {
  if (STYLES[read(dir).style]?.vertex) { onStep?.('Casting the characters'); await ensureCast(dir).catch(() => {}); }
  const queue = [...ids], busy = [];
  const worker = async (first = true) => {
    while (queue.length) {
      const id = queue.shift();
      const p = read(dir), shot = p.shots.find(s => s.id === id);
      if (!shot) continue;
      try {
        const r = await drawBoard(dir, p, shot, { model });
        const fresh = read(dir), s = fresh.shots.find(x => x.id === id);
        if (s) { Object.assign(s, { board: r.board, box: r.box, fallback: r.fallback }); fresh.cost = (fresh.cost || 0) + (r.cost || 0); saveProduction(dir, fresh); }
        onShot?.(id, null);
      } catch (e) {
        if (first && e.code === 429) busy.push(id);
        else onShot?.(id, e);
      }
    }
  };
  // generated frames share a per-minute quota, so they go two at a time; frames refused as busy get one more pass,
  // one at a time, after a pause
  await Promise.all(Array.from({ length: STYLES[read(dir).style]?.vertex ? 2 : 4 }, () => worker()));
  if (busy.length) {
    await new Promise(res => setTimeout(res, 20000));
    queue.push(...busy.splice(0));
    await worker(false);
  }
}

// —— what the editor shows alongside the production ——
export function review(p) {
  const brief = `${p.brief} ${p.notes || ''}`;
  const shots = (p.shots || []).map(s => ({ id: s.id, unsupported: unsupportedNumbers(`${s.vo} ${s.super}`, s.proof || [], brief) }));
  const total = (p.shots || []).reduce((t, s) => t + (+s.dur || 0), 0);
  const shoot = (p.shots || []).reduce((t, s) => t + (+s.dur || 0) * (RATE[s.engine] || 0), 0);
  return { shots, total, shoot: Math.round(shoot * 100) / 100 };
}

// —— 4. the animatic: a quick film (templates/animatic) built from the boards ——
export function animaticScript(p) {
  return {
    title: (p.title || 'Animatic') + ' (animatic)', accent: '#0a84ff', bpm: p.music?.bpm || 96,
    scenes: p.shots.map((s, i) => ({ type: 'shot', n: i + 1, text: s.super || '', narration: s.vo || '', dur: +s.dur || 2.5, size: s.size, move: s.move, engine: s.engine,
      board: s.board || null, image: s.product >= 0 ? s.product : undefined, box: s.box || undefined })),
  };
}
